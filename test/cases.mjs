function rng(seed) {
  let s = seed >>> 0 || 1;
  return () => {
    s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0;
    return s / 4294967296;
  };
}

export function generateCases(seed, count) {
  const r = rng(seed);
  const int = (n) => Math.floor(r() * n);
  const pick = (a) => a[int(a.length)];
  const octet = () => pick([0, 1, 10, 127, 128, 169, 172, 192, 224, 254, 255, int(256), int(256), int(256), 256, 300, 999]);
  const quad = () => [octet(), octet(), octet(), octet()].join('.');
  const realQuad = () => [int(256), int(256), int(256), int(256)].join('.');
  const prefix = () => int(r() < 0.9 ? 33 : 100);
  const dotted = (p) => { const n = p === 0 ? 0 : (0xffffffff << (32 - p)) >>> 0; return [24, 16, 8, 0].map((s) => (n >>> s) & 255).join('.'); };
  const hex8 = (v) => (v >>> 0).toString(16).padStart(8, '0');
  const h16 = () => (r() < 0.4 ? '0' : int(65536).toString(16));
  const v6 = () => {
    const parts = Array.from({ length: 8 }, h16);
    if (r() < 0.6) { const a = int(8), b = a + int(8 - a); parts.splice(a, b - a + 1, ''); if (a === 0) parts.unshift(''); }
    return parts.join(':') || '::';
  };
  const address = () => pick([quad, realQuad, realQuad, realQuad, () => '0x' + hex8(int(2 ** 32)), () => hex8(int(2 ** 32)),
    v6, () => pick(['', 'x', '1.2.3', '1..2.3', 'a.b.c.d', '-1.2.3.4', '01.02.03.004', '1.2.3.4.5'])])();
  const mask = () => pick([
    () => String(prefix()), () => '/' + prefix(), () => dotted(int(33)), () => dotted(int(33)),
    () => { const p = int(33); return [24, 16, 8, 0].map((s) => ((~((0xffffffff << (32 - p)) >>> 0) >>> s) & 255) >>> 0).join('.'); },
    () => '0x' + hex8(p2mask(int(33))), () => hex8(p2mask(int(33))), quad, () => pick(['', '-1', '1e1', 'ff', '0x', '255.255.255.0.0']),
  ])();
  const p2mask = (p) => (p === 0 ? 0 : (0xffffffff << (32 - p)) >>> 0);
  const flag = () => pick(['-n', '-c', '-b', '-h', '-r', '--class', '-v', '--help', '-x', '--nocolor', '--color', '--nobinary', '-nb', '-cb', '--range']);

  const cases = [];
  for (let k = 0; k < count; k++) {
    const kind = int(10);
    let argv;
    if (kind < 4) { // address/mask
      argv = [address() + '/' + mask()];
      if (r() < 0.4) argv.push(mask());
    } else if (kind < 6) { // separate args
      argv = [address(), mask()];
      if (r() < 0.6) argv.push(mask());
    } else if (kind < 7) { // ranges
      const a = pick([realQuad, quad, v6])(), b = pick([realQuad, quad, v6])();
      argv = pick([[a + '-' + b], [a, '-', b], ['-r', a, b]]);
    } else if (kind < 8) { // split
      const sizes = Array.from({ length: 1 + int(5) }, () => String(pick([0, 1, 2, 5, 14, 30, 62, 100, 254, 1000, 70000, int(5000)])));
      argv = ['-s', ...sizes, realQuad() + '/' + int(33)];
      if (r() < 0.3) argv = [argv[argv.length - 1], ...argv.slice(0, -1)];
    } else if (kind < 9) { // ipv6
      argv = [v6() + (r() < 0.7 ? '/' + int(140) : '')];
    } else { // single address
      argv = [address()];
    }
    if (r() < 0.35) {
      const f = flag();
      if (f === '--help' || f === '-v') { if (r() < 0.8) argv.unshift('-n'); else argv.unshift(f); }
      else argv.splice(int(argv.length + 1), 0, f);
    }
    if (kind < 6 && r() < 0.1) argv.splice(int(argv.length + 1), 0, '-s', String(1 + int(300)));
    cases.push(argv);
  }
  return cases;
}

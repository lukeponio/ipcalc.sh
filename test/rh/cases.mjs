function rng(seed) {
  let s = seed >>> 0 || 1;
  return () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
}

export function generateCases(seed, count) {
  const r = rng(seed);
  const int = (n) => Math.floor(r() * n);
  const pick = (a) => a[int(a.length)];
  const octet = () => pick([0, 1, 10, 100, 127, 169, 172, 192, 198, 203, 224, 240, 255, int(256), int(256), int(256), 256, '01']);
  const quad = () => (r() < 0.85 ? [int(256), int(256), int(256), int(256)] : [octet(), octet(), octet(), octet()]).join('.');
  const dotted = (p) => { const n = p === 0 ? 0 : (0xffffffff << (32 - p)) >>> 0; return [24, 16, 8, 0].map((s) => (n >>> s) & 255).join('.'); };
  const h16 = () => (r() < 0.45 ? '0' : int(65536).toString(16));
  const v6 = () => {
    if (r() < 0.15) return pick(['::1', '::', '2001:db8::', 'fe80::1', 'ff02::1', '::ffff:10.0.0.1', '64:ff9b::1', '2002::', 'fd00::', '2001::', '2001:2::1']);
    const parts = Array.from({ length: 8 }, h16);
    if (r() < 0.6) { const a = int(8), b = a + int(8 - a); parts.splice(a, b - a + 1, ''); if (a === 0) parts.unshift(''); }
    return parts.join(':') || '::';
  };
  const prefix4 = () => pick([String(int(33)), String(int(33)), dotted(int(33)), quad(), String(int(40)), '0x' + int(33).toString(16), '0' + int(40).toString(8), '-1', 'x']);
  const prefix6 = () => pick([String(int(129)), String(int(129)), String(int(140)), String(4 * int(33)), '0x' + int(129).toString(16)]);
  const info = ['-i', '--all-info', '-a', '-b', '-m', '-n', '-p', '--minaddr', '--maxaddr', '--addresses', '--addrspace', '--reverse-dns', '--class-prefix', '-g'];
  const mods = ['-j', '--no-decorate', '-s', '-4', '-6', '-c'];

  const cases = [];
  for (let k = 0; k < count; k++) {
    const kind = int(10);
    let argv;
    const v4 = r() < 0.65;
    const addr = v4 ? quad() + (r() < 0.8 ? '/' + prefix4() : '') : v6() + (r() < 0.75 ? '/' + prefix6() : '');
    if (kind < 5) {
      argv = [addr];
      for (let n = int(4); n > 0; n--) argv.splice(int(argv.length + 1), 0, pick(r() < 0.7 ? info : mods));
    } else if (kind < 7) {
      // split; keep the subnet count small enough for the reference tool
      const base = v4 ? int(33) : int(129);
      const sp = Math.min(v4 ? 32 : 128, base + int(9)) - (r() < 0.1 ? 3 : 0);
      argv = ['-S', String(sp), (v4 ? quad() : v6()) + '/' + base];
      if (r() < 0.4) argv.push(pick(['-j', '--no-decorate', '-6', '-s']));
    } else if (kind < 9) {
      // deaggregate
      let a, b;
      if (v4) { const x = int(2 ** 32 - 4096); a = x; b = x + int(4096); [a, b] = [a, b].map((n) => [24, 16, 8, 0].map((s) => (n >>> s) & 255).join('.')); }
      else { const pre = v6().replace(/::.*$/, ''); a = (pre || '2001:db8') + '::' + int(65536).toString(16); b = (pre || '2001:db8') + '::' + (int(65536) | 0x10000 ? int(65536).toString(16) : '0'); }
      if (r() < 0.2) [a, b] = [b, a];
      argv = ['-d', a + pick(['-', '-', ' - ', '--']) + b];
      if (r() < 0.4) argv.push(pick(['-j', '--no-decorate', '-6', '-4', '-s']));
    } else {
      argv = pick([[addr, prefix4()], [quad(), prefix6()], [addr, '-c'], ['-c', addr], [addr, '--bogus'], ['-' + pick(['x', 'q', 'cz', 'iS']), addr]]);
    }
    cases.push(argv);
  }
  return cases;
}
